/**
 * @file precise_time.h
 * @version 1.0.0
 * @date    2026-06-24
 *
 * @brief Высокоточное измерение коротких интервалов времени (~микросекунды).
 *
 * Описание
 * --------
 * Модуль предоставляет средства для точного измерения промежутков времени
 * на основе аппаратного счётчика тактов процессора (DWT CYCCNT в Cortex-M).
 * Предназначен для:
 *   - Измерения длительности операций с микросекундной точностью.
 *   - Блокирующих задержек в микросекундах.
 *   - Вычисления разницы между двумя временными метками.
 *
 * Ограничения (Важно!)
 * --------------------
 * Счётчик DWT->CYCCNT является 32-битным, поэтому переполняется каждые:
 *
 *     период = 2^32 / system_core_clock
 *           ~ 4 294 967 296 / 168 000 000 ≈ 25.57 секунд (при 168 МГц)
 *
 * Это накладывает жёсткие ограничения:
 *
 *   1. Функции pt_to_us(cycles), pt_to_ms(cycles) возвращают абсолютное время
 *      и НЕ должны использоваться для вычисления разницы — при переполнении
 *      счётчика значение резко падает, и беззнаковая арифметика ломается,
 *      так как диапазон сжат (0 → ~25 565 281 мкс, а не полный uint32_t).
 *
 *   2. Для корректного вычисления интервалов используйте:
 *        pt_elapsed_us()     — сколько прошло от метки до сейчас.
 *        pt_diff_us(st0,st1) — разница между двумя любыми метками.
 *      Эти функции работают с сырыми циклами, поэтому беззнаковая арифметика
 *      корректна (полный диапазон 32 бит).
 *
 *   3. Максимальный интервал: ~25.57с (при 168 МГц). Для более длительных
 *      промежутков используйте RTC или системный таймер.
 *
 * Пример использования
 * -------------------
 *     pt_init();
 *
 *     // Измерение длительности операции
 *     uint32_t t0 = pt_stamp();
 *     some_operation();
 *     uint32_t elapsed = pt_elapsed_us(t0);
 *
 *     // Блокирующая задержка
 *     pt_delay_us(100);  // 100 мкс
 *
 *     // Разница между двумя метками (без текущего времени)
 *     uint32_t t_start = pt_stamp();
 *     // ...
 *     uint32_t t_end   = pt_stamp();
 *     uint32_t diff = pt_diff_us(t_start, t_end);
 *
 * @note Точность зависит от system_core_clock. При 168 МГц — ~6 нс на тик. Плюс некоторые накладные расходы.
 */

#ifndef PRECISE_TIME_H
#define PRECISE_TIME_H

#include <stdint.h>
#include "stm32f407xx.h"

// TODO: Зависимость от глобальной переменной. Рассмотреть замену на SystemCoreClock (CMSIS) или макрос.
extern uint32_t system_core_clock;

/* ---------- Конфигурация ---------- */

/** Максимальный корректный интервал в микросекундах (~период переполнения).
 *  При 168 МГц: ~25 565 281 мкс ≈ 25.57 секунд.                          */
#define PT_MAX_INTERVAL_US   (0xFFFFFFFFU / (system_core_clock / 1000000U))

/** Делитель циклов -> микросекунды (тиков счётчика на одну микросекунду). */
#define PT_CYCLES_PER_US     (system_core_clock / 1000000U)

/* ---------- Публичный API ---------- */

/** @brief Инициализация высокоточного счётчика.
 *
 * Разрешает использование DWT CYCCNT и сбрасывает его в ноль.
 * Вызвать один раз при старте системы.                             */
static inline void pt_init(void)
{
    CoreDebug->DEMCR |= CoreDebug_DEMCR_TRCENA_Msk;
    DWT->CYCCNT       = 0;
    DWT->CTRL        |= DWT_CTRL_CYCCNTENA_Msk;
}

/** @brief Получить текущую метку времени (сырые циклы).
 *
 * @return Значение DWT->CYCCNT на момент вызова.
 *         Используется с pt_elapsed_us(), pt_diff_us().             */
static inline uint32_t pt_stamp(void)
{
    return DWT->CYCCNT;
}

/** @brief Вычислить прошедшее время в микросекундах от метки до сейчас.
 *
 * Корректно обрабатывает переполнение 32-битного счётчика
 * (беззнаковая арифметика).
 *
 * @param stamp  Метка, полученная ранее через pt_stamp().
 * @return Прошедшее время в микросекундах.
 * @note Интервал должен быть < PT_MAX_INTERVAL_US (~25.57с).       */
static inline uint32_t pt_elapsed_us(uint32_t stamp)
{
    uint32_t elapsed_cycles = DWT->CYCCNT - stamp;
    return elapsed_cycles / PT_CYCLES_PER_US;
}

/** @brief Вычислить разницу в микросекундах между двумя метками.
 *
 * Корректно обрабатывает переполнение 32-битного счётчика.
 *
 * @param start  Старшая (более ранняя) метка (pt_stamp()).
 * @param end    Младшая (более поздняя) метка (pt_stamp()).
 * @return Разница в микросекундах.
 * @note Интервал должен быть < PT_MAX_INTERVAL_US (~25.57с).       */
static inline uint32_t pt_diff_us(uint32_t start, uint32_t end)
{
    uint32_t elapsed_cycles = end - start;
    return elapsed_cycles / PT_CYCLES_PER_US;
}

/** @brief Блокирующая задержка в микросекундах.
 *
 * Корректно обрабатывает переполнение счётчика.
 *
 * @param us  Длительность задержки в микросекундах.                 */
static inline void pt_delay_us(uint32_t us)
{
    uint32_t cycles = (uint32_t)((uint64_t)us * PT_CYCLES_PER_US);
    uint32_t start  = DWT->CYCCNT;
    while ((DWT->CYCCNT - start) < cycles)
        /* empty */;
}

/* ---------- Convenience-функции (с ограничениями!) ---------- */

/** @brief Конвертировать сырые циклы в микросекунды.
 *
 * @param cycles  Значение DWT->CYCCNT.
 * @return Приблизительное время в микросекундах с момента инициализации
 *         или последнего переполнения.
 *
 * @warning НЕ использовать для вычисления разниц! При переполнении счётчика
 *          значение резко падает, и беззнаковая арифметика ломается,
 *          так как диапазон сжат (0 → ~25 565 281, а не UINT32_MAX).
 *          Только для логирования/отладки текущего значения.         */
static inline uint32_t pt_to_us(uint32_t cycles)
{
    return cycles / PT_CYCLES_PER_US;
}

/** @brief Получить текущее значение счётчика в микросекундах.
 *
 * Эквивалентно: pt_to_us(DWT->CYCCNT).
 *
 * @warning См. предупреждение в pt_to_us().                         */
static inline uint32_t pt_now_us(void)
{
    return pt_to_us(DWT->CYCCNT);
}

/** @brief Получить текущее значение счётчика в миллисекундах.
 *
 * Эквивалентно: pt_now_us() / 1000.
 *
 * @warning См. предупреждение в pt_to_us().                         */
static inline uint32_t pt_now_ms(void)
{
    return pt_to_us(DWT->CYCCNT) / 1000U;
}

#endif /* PRECISE_TIME_H */